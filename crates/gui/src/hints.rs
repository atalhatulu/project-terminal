pub fn get_command_description(cmd: &str) -> Option<&'static str> {
    match cmd {
        // Dosya ve Dizin İşlemleri
        "ls" => Some("Dizin içeriğini listeler (list)"),
        "cd" => Some("Çalışma dizinini değiştirir (change directory)"),
        "pwd" => Some("Mevcut dizinin tam yolunu yazdırır (print working dir)"),
        "mkdir" => Some("Yeni bir dizin oluşturur (make directory)"),
        "rmdir" => Some("Boş dizini siler (remove directory)"),
        "rm" => Some("Dosya veya dizinleri siler (remove)"),
        "cp" => Some("Dosya ve dizinleri kopyalar (copy)"),
        "mv" => Some("Dosyaları taşır veya yeniden adlandırır (move)"),
        "touch" => Some("Boş dosya oluşturur / erişim zamanını günceller"),
        "cat" => Some("Dosya içeriğini ekrana basar / birleştirir (concatenate)"),
        "less" => Some("Dosya içeriğini sayfalar halinde okur"),
        "more" => Some("Dosyayı parça parça gösterir"),
        "head" => Some("Dosyanın ilk satırlarını gösterir"),
        "tail" => Some("Dosyanın son satırlarını gösterir (takip: -f)"),
        "find" => Some("Dosya ve dizin arar"),
        "locate" => Some("Veritabanından hızlı dosya arar"),
        "grep" => Some("Metin içinde desen/kelime arar"),
        "chmod" => Some("Dosya izinlerini değiştirir (change mode)"),
        "chown" => Some("Dosya sahibini değiştirir (change owner)"),
        "tar" => Some("Arşiv dosyası oluşturur / açar (tape archive)"),
        "zip" => Some("Dosyaları ZIP ile sıkıştırır"),
        "unzip" => Some("ZIP arşivini açar"),

        // Sistem ve Süreç Yönetimi
        "ps" => Some("Çalışan süreçleri listeler (process status)"),
        "top" => Some("Anlık sistem ve işlemci kullanımını gösterir"),
        "htop" => Some("Gelişmiş görsel sistem monitörü"),
        "kill" => Some("Sürece sonlandırma sinyali gönderir"),
        "killall" => Some("İsme göre tüm süreçleri sonlandırır"),
        "sudo" => Some("Yönetici yetkileriyle komut çalıştırır (superuser do)"),
        "su" => Some("Kullanıcı değiştirir (switch user)"),
        "whoami" => Some("Aktif kullanıcı adını gösterir"),
        "df" => Some("Disk alanı kullanımını gösterir (disk free)"),
        "du" => Some("Dizinlerin disk boyutunu hesaplar (disk usage)"),
        "free" => Some("RAM ve takas alanı kullanımını gösterir"),
        "uname" => Some("İşletim sistemi ve çekirdek bilgilerini basar"),
        "uptime" => Some("Sistemin ne kadar süredir açık olduğunu gösterir"),
        "clear" => Some("Terminal ekranını temizler"),
        "history" => Some("Daha önce girilen komut geçmişini listeler"),
        "reboot" => Some("Sistemi yeniden başlatır"),
        "shutdown" => Some("Sistemi kapatır"),

        // Ağ ve İletişim
        "ping" => Some("Ağ bağlantısını ve gecikmeyi test eder"),
        "curl" => Some("URL üzerinden veri aktarır / indirir"),
        "wget" => Some("İnternetten dosya indirir"),
        "ssh" => Some("Uzak sunucuya güvenli kabuk bağlantısı açar (secure shell)"),
        "scp" => Some("SSH üzerinden güvenli dosya kopyalar"),
        "rsync" => Some("Hızlı dosya ve dizin eşitleme aracı"),
        "netstat" => Some("Ağ bağlantılarını ve dinlenen portları gösterir"),
        "ss" => Some("Modern soket ve ağ durum inceleme aracı"),
        "ip" => Some("Ağ arayüzlerini ve yönlendirmeleri yönetir"),
        "ifconfig" => Some("Ağ kartı yapılandırmasını gösterir"),

        // Geliştirici ve Paket Araçları
        "git" => Some("Dağıtık sürüm kontrol sistemi"),
        "cargo" => Some("Rust paket yöneticisi ve derleyicisi"),
        "rustc" => Some("Rust programlama dili derleyicisi"),
        "python" | "python3" => Some("Python yorumlayıcısı"),
        "node" => Some("Node.js JavaScript çalışma ortamı"),
        "npm" => Some("Node.js paket yöneticisi"),
        "yarn" | "pnpm" => Some("Hızlı JavaScript paket yöneticisi"),
        "docker" => Some("Konteyner yönetim platformu"),
        "docker-compose" => Some("Çoklu konteyner orkestrasyonu"),
        "make" => Some("Makefile ile otomatik yazılım derleme aracı"),
        "gcc" | "g++" | "clang" => Some("C / C++ derleyicisi"),
        "apt" | "apt-get" => Some("Debian/Ubuntu paket yönetim aracı"),
        "pacman" => Some("Arch Linux paket yöneticisi"),
        "dnf" => Some("Fedora/RHEL paket yöneticisi"),

        _ => None,
    }
}
