pub fn get_command_description(cmd: &str) -> Option<&'static str> {
    match cmd {
        // Dosya ve Dizin İşlemleri
        "ls" => Some("dizin listele"),
        "cd" => Some("dizin değiştir"),
        "pwd" => Some("aktif yol"),
        "mkdir" => Some("yeni dizin"),
        "rmdir" => Some("boş dizin sil"),
        "rm" => Some("dosya sil"),
        "cp" => Some("kopyala"),
        "mv" => Some("taşı / adlandır"),
        "touch" => Some("boş dosya aç"),
        "cat" => Some("dosyayı yazdır"),
        "less" => Some("sayfala"),
        "more" => Some("sayfala"),
        "head" => Some("ilk satırlar"),
        "tail" => Some("son satırlar"),
        "find" => Some("dosya ara"),
        "locate" => Some("hızlı ara"),
        "grep" => Some("desen ara"),
        "chmod" => Some("izinleri ayarla"),
        "chown" => Some("sahibi değiştir"),
        "tar" => Some("arşivle / aç"),
        "zip" => Some("zip sıkıştır"),
        "unzip" => Some("zip aç"),
        "tree" => Some("ağaç görünümü"),

        // Sistem ve Süreç Yönetimi
        "ps" => Some("süreçler"),
        "top" | "htop" | "btop" => Some("sistem monitörü"),
        "kill" | "killall" => Some("süreci durdur"),
        "sudo" => Some("yönetici yetkisi"),
        "su" => Some("kullanıcı değiştir"),
        "whoami" => Some("aktif kullanıcı"),
        "df" => Some("disk alanı"),
        "du" => Some("dizin boyutu"),
        "free" => Some("ram kullanımı"),
        "uname" => Some("çekirdek bilgisi"),
        "uptime" => Some("çalışma süresi"),
        "clear" => Some("temizle"),
        "history" => Some("geçmiş"),
        "reboot" => Some("yeniden başlat"),
        "shutdown" => Some("kapat"),

        // Ağ ve İletişim
        "ping" => Some("ağ gecikmesi"),
        "curl" | "wget" => Some("ağdan indir"),
        "ssh" => Some("güvenli kabuk"),
        "scp" | "rsync" => Some("ağdan kopyala"),
        "netstat" | "ss" => Some("açık portlar"),
        "ip" | "ifconfig" => Some("ağ kartı"),

        // Geliştirici ve Paket Araçları
        "git" => Some("sürüm kontrol"),
        "cargo" => Some("rust paketi"),
        "rustc" => Some("rust derleyici"),
        "python" | "python3" => Some("python"),
        "node" => Some("nodejs"),
        "npm" | "yarn" | "pnpm" => Some("paket yöneticisi"),
        "docker" => Some("konteyner"),
        "docker-compose" => Some("orkestrasyon"),
        "make" => Some("derleme"),
        "gcc" | "g++" | "clang" => Some("c/c++ derleyici"),
        "apt" | "apt-get" | "pacman" | "dnf" => Some("paket kur"),

        _ => None,
    }
}
